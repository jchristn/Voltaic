        /// <summary>
        /// Handles <c>GetTaskPushNotificationConfig</c>: returns one stored configuration.
        /// </summary>
        /// <param name="request">The request.</param>
        /// <param name="token">Cancellation token for the request.</param>
        /// <returns>The configuration.</returns>
        /// <exception cref="A2AProtocolException">Thrown with <see cref="A2AErrorCode.PushNotificationNotSupported"/> when push notifications are not advertised, <see cref="A2AErrorCode.InvalidParams"/> when an ID is missing, or <see cref="A2AErrorCode.TaskNotFound"/> when the task does not exist or has no configuration with that ID (the A2A specification uses the not-found error for both).</exception>
        public async Task<TaskPushNotificationConfig> GetTaskPushNotificationConfigAsync(GetTaskPushNotificationConfigRequest request, CancellationToken token = default)
        {
            EnsurePushNotificationsSupported();
            if (request == null || String.IsNullOrWhiteSpace(request.TaskId)) throw A2AProtocolException.InvalidParams("TaskId is required.");
            if (String.IsNullOrWhiteSpace(request.ConfigId)) throw A2AProtocolException.InvalidParams("The push notification configuration ID is required.");
