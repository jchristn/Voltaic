    /// <summary>
    /// Implements an A2A agent's behavior. <see cref="A2AHttpServer"/> and <see cref="A2AGrpcServer"/> call it
    /// for every <c>SendMessage</c>, <c>SendStreamingMessage</c>, and <c>CancelTask</c> request, and apply the
    /// events it writes to the task store. Implementations must be thread-safe: the server invokes them
    /// concurrently for concurrent requests, each on a background task.
    /// </summary>
    public interface IA2AAgentHandler
    {
        /// <summary>
        /// Handles a new or continuing message. Write task status updates, artifacts, or a direct
        /// <see cref="Message"/> reply to <paramref name="eventQueue"/>, typically through
        /// <see cref="A2ATaskUpdater"/>. The server completes the queue when this method returns, so do not
        /// call <see cref="A2AAgentEventQueue.Complete"/> yourself. For a non-streaming request the first event
        /// determines the response shape (a task or a message). Throwing fails the request; with
        /// <c>returnImmediately</c> the task is marked failed instead.
        /// </summary>
        /// <param name="context">The request context: the message, task and context IDs, configuration, and authenticated caller. Never null.</param>
        /// <param name="eventQueue">The queue that receives the agent's events. Never null.</param>
        /// <param name="token">Cancellation token for the request.</param>
        /// <returns>A task that completes when the agent has finished handling the message.</returns>
        Task ExecuteAsync(A2ARequestContext context, A2AAgentEventQueue eventQueue, CancellationToken token);

        /// <summary>
        /// Handles a <c>CancelTask</c> request for a task that is not yet terminal. The default implementation
        /// writes a <see cref="TaskState.Canceled"/> status update. Override it to stop in-flight work first, or
        /// to write a different final state.
        /// </summary>
        /// <param name="context">The context of the task being canceled; <see cref="A2ARequestContext.ExistingTask"/> is set. Never null.</param>
        /// <param name="eventQueue">The queue that receives the cancellation events. Never null.</param>
        /// <param name="token">Cancellation token for the request.</param>
        /// <returns>A task that completes when the cancellation events have been written.</returns>
        async Task CancelAsync(A2ARequestContext context, A2AAgentEventQueue eventQueue, CancellationToken token)
        {
            A2ATaskUpdater updater = new A2ATaskUpdater(eventQueue, context.TaskId, context.ContextId);
            await updater.CancelAsync(token: token).ConfigureAwait(false);
        }
    }

    /// <summary>
    /// Describes the request an <see cref="IA2AAgentHandler"/> is handling. The server builds a new instance per
    /// request; it is not shared between requests and is not thread-safe.
    /// </summary>
    public sealed class A2ARequestContext
    {
        /// <summary>
        /// Gets or sets the incoming message, with its <c>taskId</c> and <c>contextId</c> filled in by the server.
        /// For a cancellation it is the task's last history message. Default is an empty message; never null.
        /// </summary>
        public Message Message { get; set; } = new Message();

        /// <summary>
        /// Gets or sets the original <c>SendMessage</c> request. Null for cancellations.
        /// </summary>
        public SendMessageRequest? SendMessageRequest { get; set; }

        /// <summary>
        /// Gets or sets the stored task this message continues or cancels. Null when the message starts a new task.
        /// </summary>
        public AgentTask? ExistingTask { get; set; }

        /// <summary>
        /// Gets or sets the task ID: the one the message referenced, or a new ID generated by the server.
        /// Default is an empty string.
        /// </summary>
        public string TaskId { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the context ID: the message's, the existing task's, or a new ID generated by the server.
        /// Default is an empty string.
        /// </summary>
        public string ContextId { get; set; } = string.Empty;

        /// <summary>
        /// Gets a value indicating whether the message continues an existing task (<see cref="ExistingTask"/> is not null).
        /// </summary>
        public bool IsContinuation => ExistingTask != null;

        /// <summary>
        /// Gets or sets a value indicating whether the client asked for a streaming response
        /// (<c>SendStreamingMessage</c>). Default is false.
        /// </summary>
        public bool StreamingResponse { get; set; }

        /// <summary>
        /// Gets or sets the request's send configuration (for example <c>returnImmediately</c> and
        /// <c>historyLength</c>). Null when the client sent none.
        /// </summary>
        public SendMessageConfiguration? Configuration { get; set; }

        /// <summary>
        /// Gets or sets the request metadata sent by the client. Null when the client sent none.
        /// </summary>
        public Dictionary<string, object?>? Metadata { get; set; }

        /// <summary>
        /// Gets or sets the authenticated principal for the request, copied from the server's
        /// <c>AuthenticationHandler</c> result. Null when the request was not authenticated (no handler
        /// configured, or a public Agent Card request). Host-defined and opaque to Voltaic.
        /// </summary>
        public string? Principal { get; set; }

        /// <summary>
        /// Gets or sets the host-defined claims for the authenticated caller (for example tenant, user, or
        /// role), copied from the server's <c>AuthenticationHandler</c> result. Null when the request was
        /// not authenticated or the result carried no claims.
        /// </summary>
        public IReadOnlyDictionary<string, string>? Claims { get; set; }
    }

    /// <summary>
    /// An unbounded, single-use queue of agent events (<see cref="StreamResponse"/>) between an
    /// <see cref="IA2AAgentHandler"/> and the server. Writing and reading are thread-safe; a queue is read once.
    /// </summary>
    public sealed class A2AAgentEventQueue
    {
        private readonly Channel<StreamResponse> _Channel = Channel.CreateUnbounded<StreamResponse>();

        /// <summary>
        /// Writes an event to the queue.
        /// </summary>
        /// <param name="response">The event: a task, message, status update, or artifact update. Must not be null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        /// <exception cref="System.Threading.Channels.ChannelClosedException">Thrown when the queue has been completed.</exception>
        public ValueTask WriteAsync(StreamResponse response, CancellationToken token = default)
        {
            return _Channel.Writer.WriteAsync(response, token);
        }

        /// <summary>
        /// Marks the queue complete so readers finish after the queued events. Calling it more than once has no
        /// further effect.
        /// </summary>
        /// <param name="exception">An optional error; when set, readers throw it after draining the queue. Default is null.</param>
        public void Complete(Exception? exception = null)
        {
            _Channel.Writer.TryComplete(exception);
        }

        /// <summary>
        /// Reads every event until the queue is completed.
        /// </summary>
        /// <param name="token">Cancellation token for the enumeration.</param>
        /// <returns>The queued events, in the order they were written.</returns>
        public IAsyncEnumerable<StreamResponse> ReadAllAsync(CancellationToken token = default)
        {
            return _Channel.Reader.ReadAllAsync(token);
        }
    }

    /// <summary>
    /// Helper that writes task status and artifact events for one task to an <see cref="A2AAgentEventQueue"/>.
    /// Each status update is stamped with the current UTC time. Thread safety matches the underlying queue.
    /// </summary>
    public sealed class A2ATaskUpdater
    {
        private readonly A2AAgentEventQueue _EventQueue;
        private readonly string _TaskId;
        private readonly string _ContextId;

        /// <summary>
        /// Initializes a new instance of the <see cref="A2ATaskUpdater"/> class.
        /// </summary>
        /// <param name="eventQueue">The queue to write to.</param>
        /// <param name="taskId">The task ID stamped on every event, usually <see cref="A2ARequestContext.TaskId"/>.</param>
        /// <param name="contextId">The context ID stamped on every event, usually <see cref="A2ARequestContext.ContextId"/>.</param>
        /// <exception cref="ArgumentNullException">Thrown when any argument is null.</exception>
        public A2ATaskUpdater(A2AAgentEventQueue eventQueue, string taskId, string contextId)
        {
            _EventQueue = eventQueue ?? throw new ArgumentNullException(nameof(eventQueue));
            _TaskId = taskId ?? throw new ArgumentNullException(nameof(taskId));
            _ContextId = contextId ?? throw new ArgumentNullException(nameof(contextId));
        }

        /// <summary>
        /// Writes a <see cref="TaskState.Submitted"/> status update.
        /// </summary>
        /// <param name="message">An optional status message. Default is null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask SubmitAsync(Message? message = null, CancellationToken token = default)
        {
            return UpdateStatusAsync(TaskState.Submitted, message, token);
        }

        /// <summary>
        /// Writes a <see cref="TaskState.Working"/> status update.
        /// </summary>
        /// <param name="message">An optional status message. Default is null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask StartAsync(Message? message = null, CancellationToken token = default)
        {
            return UpdateStatusAsync(TaskState.Working, message, token);
        }

        /// <summary>
        /// Writes a <see cref="TaskState.Completed"/> status update, a terminal state.
        /// </summary>
        /// <param name="message">An optional status message. Default is null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask CompleteAsync(Message? message = null, CancellationToken token = default)
        {
            return UpdateStatusAsync(TaskState.Completed, message, token);
        }

        /// <summary>
        /// Writes a <see cref="TaskState.Failed"/> status update, a terminal state.
        /// </summary>
        /// <param name="message">An optional status message. Default is null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask FailAsync(Message? message = null, CancellationToken token = default)
        {
            return UpdateStatusAsync(TaskState.Failed, message, token);
        }

        /// <summary>
        /// Writes a <see cref="TaskState.Canceled"/> status update, a terminal state.
        /// </summary>
        /// <param name="message">An optional status message. Default is null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask CancelAsync(Message? message = null, CancellationToken token = default)
        {
            return UpdateStatusAsync(TaskState.Canceled, message, token);
        }

        /// <summary>
        /// Writes a status update with the given state.
        /// </summary>
        /// <param name="state">The new task state.</param>
        /// <param name="message">An optional status message. Default is null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask UpdateStatusAsync(TaskState state, Message? message = null, CancellationToken token = default)
        {
            return _EventQueue.WriteAsync(new StreamResponse
            {
                StatusUpdate = new TaskStatusUpdateEvent
                {
                    TaskId = _TaskId,
                    ContextId = _ContextId,
                    Status = new TaskStatus
                    {
                        State = state,
                        Message = message,
                        Timestamp = DateTimeOffset.UtcNow
                    }
                }
            }, token);
        }

        /// <summary>
        /// Writes an artifact update.
        /// </summary>
        /// <param name="artifact">The artifact, or an artifact chunk when streaming it in parts.</param>
        /// <param name="append">True to append the parts to a previously sent artifact with the same ID; false (the default) to replace it.</param>
        /// <param name="lastChunk">True (the default) when this is the final chunk of the artifact.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask AddArtifactAsync(Artifact artifact, bool append = false, bool lastChunk = true, CancellationToken token = default)
        {
            return _EventQueue.WriteAsync(new StreamResponse
            {
                ArtifactUpdate = new TaskArtifactUpdateEvent
                {
                    TaskId = _TaskId,
                    ContextId = _ContextId,
                    Artifact = artifact,
                    Append = append,
                    LastChunk = lastChunk
                }
            }, token);
        }

        /// <summary>
        /// Writes a direct message reply. For a non-streaming request whose first event is a message, the
        /// response is that message rather than a task.
        /// </summary>
        /// <param name="message">The reply message.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the event has been queued.</returns>
        public ValueTask ReturnMessageAsync(Message message, CancellationToken token = default)
        {
            return _EventQueue.WriteAsync(new StreamResponse { Message = message }, token);
        }
    }

    /// <summary>
    /// Persists A2A tasks for <see cref="A2AHttpServer"/> and <see cref="A2AGrpcServer"/>. Implementations must be
    /// thread-safe, and should store and return copies so callers cannot mutate stored state.
    /// <see cref="InMemoryA2ATaskStore"/> is the default.
    /// </summary>
    public interface IA2ATaskStore
    {
        /// <summary>
        /// Gets a task by ID.
        /// </summary>
        /// <param name="taskId">The task ID.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>The task, or null when no task has that ID.</returns>
        Task<AgentTask?> GetTaskAsync(string taskId, CancellationToken token = default);

        /// <summary>
        /// Creates or replaces a task.
        /// </summary>
        /// <param name="taskId">The task ID to store it under.</param>
        /// <param name="task">The task to store.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the task has been stored.</returns>
        Task SaveTaskAsync(string taskId, AgentTask task, CancellationToken token = default);

        /// <summary>
        /// Deletes a task. Deleting an unknown ID has no effect.
        /// </summary>
        /// <param name="taskId">The task ID.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>A task that completes when the task has been deleted.</returns>
        Task DeleteTaskAsync(string taskId, CancellationToken token = default);

        /// <summary>
        /// Lists tasks, applying the request's filters (context ID, status, status timestamp), paging
        /// (page size and page token), history trimming, and artifact inclusion.
        /// </summary>
        /// <param name="request">The list request. Must not be null.</param>
        /// <param name="token">Cancellation token for the operation.</param>
        /// <returns>One page of tasks, with the total count and the next page token (empty on the last page).</returns>
        /// <exception cref="A2AProtocolException">Thrown with <see cref="A2AErrorCode.InvalidParams"/> when the page token is invalid.</exception>
        Task<ListTasksResponse> ListTasksAsync(ListTasksRequest request, CancellationToken token = default);
    }

    /// <summary>
    /// An in-memory, thread-safe <see cref="IA2ATaskStore"/>. Tasks are cloned on save and on read, so callers
    /// never share state with the store. Contents are lost when the process exits.
    /// </summary>
    public sealed class InMemoryA2ATaskStore : IA2ATaskStore
    {
        private readonly ConcurrentDictionary<string, AgentTask> _Tasks = new ConcurrentDictionary<string, AgentTask>(StringComparer.Ordinal);

        /// <summary>
        /// Gets a copy of a task by ID.
        /// </summary>
        /// <param name="taskId">The task ID. Must not be null.</param>
        /// <param name="token">Cancellation token for the operation (not observed; the operation is synchronous).</param>
        /// <returns>A copy of the task, or null when no task has that ID.</returns>
        /// <exception cref="ArgumentNullException">Thrown when <paramref name="taskId"/> is null.</exception>
        public Task<AgentTask?> GetTaskAsync(string taskId, CancellationToken token = default)
        {
            if (_Tasks.TryGetValue(taskId, out AgentTask? task))
            {
                return Task.FromResult<AgentTask?>(task.Clone());
            }

            return Task.FromResult<AgentTask?>(null);
        }

        /// <summary>
        /// Stores a copy of a task, replacing any task with the same ID.
        /// </summary>
        /// <param name="taskId">The task ID. Must not be null.</param>
        /// <param name="task">The task. Must not be null.</param>
        /// <param name="token">Cancellation token for the operation (not observed; the operation is synchronous).</param>
        /// <returns>A completed task.</returns>
        /// <exception cref="ArgumentNullException">Thrown when <paramref name="taskId"/> or <paramref name="task"/> is null.</exception>
        public Task SaveTaskAsync(string taskId, AgentTask task, CancellationToken token = default)
        {
            if (taskId == null) throw new ArgumentNullException(nameof(taskId));
            if (task == null) throw new ArgumentNullException(nameof(task));
            _Tasks[taskId] = task.Clone();
            return Task.CompletedTask;
        }

        /// <summary>
        /// Deletes a task. Deleting an unknown ID has no effect.
        /// </summary>
        /// <param name="taskId">The task ID. Must not be null.</param>
        /// <param name="token">Cancellation token for the operation (not observed; the operation is synchronous).</param>
        /// <returns>A completed task.</returns>
        /// <exception cref="ArgumentNullException">Thrown when <paramref name="taskId"/> is null.</exception>
        public Task DeleteTaskAsync(string taskId, CancellationToken token = default)
        {
            _Tasks.TryRemove(taskId, out _);
            return Task.CompletedTask;
        }

        /// <summary>
        /// Lists copies of the stored tasks, ordered by task ID (ordinal). Filters by context ID, status, and
        /// status timestamp when set. The page size defaults to 100 and is at least 1; the page token is the
        /// zero-based offset of the first task on the page. History is trimmed to
        /// <see cref="ListTasksRequest.HistoryLength"/>, and artifacts are removed when
        /// <see cref="ListTasksRequest.IncludeArtifacts"/> is false.
        /// </summary>
        /// <param name="request">The list request. Null is treated as an empty request (no filters, first page).</param>
        /// <param name="token">Cancellation token for the operation (not observed; the operation is synchronous).</param>
        /// <returns>One page of tasks, with the total count and the next page token (empty on the last page).</returns>
        /// <exception cref="A2AProtocolException">Thrown with <see cref="A2AErrorCode.InvalidParams"/> when the page token is not a non-negative integer.</exception>
        public Task<ListTasksResponse> ListTasksAsync(ListTasksRequest request, CancellationToken token = default)
        {
            request ??= new ListTasksRequest();
            IEnumerable<AgentTask> query = _Tasks.Values.Select(task => task.Clone());
            if (!String.IsNullOrEmpty(request.ContextId))
            {
                query = query.Where(task => StringComparer.Ordinal.Equals(task.ContextId, request.ContextId));
            }

            if (request.Status != null)
            {
                query = query.Where(task => task.Status.State == request.Status.Value);
            }

            if (request.StatusTimestampAfter != null)
            {
                query = query.Where(task => task.Status.Timestamp != null && task.Status.Timestamp > request.StatusTimestampAfter);
            }

            List<AgentTask> all = query.OrderBy(task => task.Id, StringComparer.Ordinal).ToList();
            int offset = 0;
            if (!String.IsNullOrEmpty(request.PageToken) && (!Int32.TryParse(request.PageToken, out offset) || offset < 0))
            {
                throw A2AProtocolException.InvalidParams($"Invalid pageToken '{request.PageToken}'.");
            }

            int pageSize = Math.Max(1, request.PageSize ?? 100);
            List<AgentTask> page = all.Skip(offset).Take(pageSize).Select(task =>
            {
                AgentTask trimmed = task.WithHistoryTrimmedTo(request.HistoryLength);
                if (request.IncludeArtifacts == false)
                {
                    trimmed.Artifacts = null;
                }

                return trimmed;
            }).ToList();

            int nextOffset = offset + page.Count;
            return Task.FromResult(new ListTasksResponse
            {
                Tasks = page,
                PageSize = page.Count,
                TotalSize = all.Count,
                NextPageToken = nextOffset < all.Count ? nextOffset.ToString() : string.Empty
            });
        }
    }

    /// <summary>
    /// Hosts an A2A v1.0 agent over HTTP: the public Agent Card at <see cref="A2AProtocol.AgentCardPath"/>, the
    /// extended Agent Card at <see cref="A2AProtocol.ExtendedAgentCardPath"/>, the JSON-RPC binding at the RPC
    /// path (default <c>/a2a</c>), the HTTP+JSON (REST) binding, and SSE streaming for streaming methods.
    /// Requests are gated in order by <see cref="RestrictToLoopbackClients"/>, <see cref="OriginPolicy"/>, CORS
    /// preflight handling, and <see cref="AuthenticationHandler"/>. When the Agent Card advertises push notifications,
    /// every task event is delivered to the task's registered webhooks (see <see cref="PushNotificationUrlValidator"/>,
    /// <see cref="PushNotificationTimeoutMs"/>, and <see cref="PushNotificationMaxAttempts"/>). JSON-RPC errors are
    /// returned with HTTP 200 and a JSON-RPC error body; HTTP+JSON errors use the A2A status mapping. Requests are handled concurrently; configure
    /// properties before calling <see cref="StartAsync"/>. The operation methods (for example
    /// <see cref="SendMessageAsync"/>) are the same ones the HTTP bindings call and can also be invoked in-process.
    /// </summary>
    public sealed class A2AHttpServer : IDisposable
    {
        private static readonly byte[] _SsePrelude = Encoding.UTF8.GetBytes(": connected\n\n");
        private readonly string _Hostname;
        private readonly int _Port;
        private readonly string _RpcPath;
        private readonly IA2ATaskStore _TaskStore;
        private readonly ConcurrentDictionary<string, ConcurrentDictionary<string, TaskPushNotificationConfig>> _PushConfigs = new ConcurrentDictionary<string, ConcurrentDictionary<string, TaskPushNotificationConfig>>(StringComparer.Ordinal);
        private readonly A2ATaskEventNotifier _Notifier = new A2ATaskEventNotifier();
        private HttpListener? _Listener;
        private CancellationTokenSource? _TokenSource;
        private Task? _ListenTask;
        private bool _IsDisposed;
        private OriginPolicy _OriginPolicy = new OriginPolicy();
        private readonly object _LifecycleLock = new object();
        private readonly object _PushLock = new object();
        private readonly Dictionary<string, Task> _PushTails = new Dictionary<string, Task>(StringComparer.Ordinal);
        private readonly CancellationTokenSource _PushShutdown = new CancellationTokenSource();
        private readonly HttpClient _PushClient;
        private Func<Uri, bool>? _PushNotificationUrlValidator;
        private int _PushNotificationTimeoutMs = 10000;
        private int _PushNotificationMaxAttempts = 3;

        /// <summary>
        /// Gets or sets the public Agent Card, served without authentication at
        /// <see cref="A2AProtocol.AgentCardPath"/>. Its <c>capabilities</c> also gate server behavior:
        /// push notification methods require <c>pushNotifications</c>, and the extended card requires
        /// <c>extendedAgentCard</c>. Set in the constructor; should not be set to null.
        /// </summary>
        public AgentCard AgentCard { get; set; }

        /// <summary>
        /// Gets or sets the extended Agent Card, returned by <c>GetExtendedAgentCard</c> and
        /// <see cref="A2AProtocol.ExtendedAgentCardPath"/> to authenticated callers when
        /// <see cref="AgentCard"/> advertises <c>capabilities.extendedAgentCard</c>. Default is null, which returns
        /// <see cref="A2AErrorCode.ExtendedAgentCardNotConfigured"/> when the capability is advertised.
        /// </summary>
        public AgentCard? ExtendedAgentCard { get; set; }

        /// <summary>
        /// Gets the agent handler that processes messages. Null until one is passed to the constructor or
        /// <see cref="RegisterHandler"/>; message and cancel requests fail with
        /// <see cref="A2AErrorCode.InternalError"/> while it is null.
        /// </summary>
        public IA2AAgentHandler? Handler { get; private set; }

        /// <summary>
        /// Gets or sets an optional asynchronous authentication handler. When set, every request that passes the
        /// loopback and origin checks, except CORS preflight (<c>OPTIONS</c>) and <c>GET</c> of the public Agent
        /// Card, is passed to it. On failure the server returns the result's
        /// <see cref="AuthenticationResult.StatusCode"/>, <see cref="AuthenticationResult.Headers"/> (for example
        /// <c>WWW-Authenticate</c>), and <see cref="AuthenticationResult.ErrorMessage"/> (default text
        /// <c>Unauthorized</c>). On success the result's <see cref="AuthenticationResult.Principal"/> and
        /// <see cref="AuthenticationResult.Claims"/> are copied onto <see cref="A2ARequestContext"/>. Default is
        /// null, which performs no authentication; the loopback and origin checks still apply.
        /// </summary>
        public Func<HttpListenerRequest, Task<AuthenticationResult>>? AuthenticationHandler { get; set; }

        /// <summary>
        /// Gets or sets whether CORS headers are sent. When enabled, a request from a browser origin that
        /// <see cref="OriginPolicy"/> allows receives <c>Access-Control-Allow-Origin</c> set to that origin (never
        /// <c>*</c>), <c>Vary: Origin</c>, and the <see cref="CorsHeaders"/>. Requests without an <c>Origin</c>
        /// header receive no CORS headers. Origins the policy rejects get HTTP 403 whether CORS is on or off.
        /// Default is true.
        /// </summary>
        public bool EnableCors { get; set; } = true;

        /// <summary>
        /// Gets or sets additional CORS headers sent to allowed browser origins when <see cref="EnableCors"/> is
        /// true. An <c>Access-Control-Allow-Origin</c> or <c>Vary</c> entry is ignored, because the allowed origin
        /// is always echoed; use <see cref="OriginPolicy"/> to choose origins.
        /// </summary>
        public Dictionary<string, string> CorsHeaders { get; set; } = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            { "Access-Control-Allow-Methods", "GET, POST, DELETE, OPTIONS" },
            { "Access-Control-Allow-Headers", HttpAccessGuard.DefaultAllowHeaders },
            { "Access-Control-Expose-Headers", "WWW-Authenticate" },
            { "Access-Control-Max-Age", "86400" }
        };

        /// <summary>
        /// Gets or sets the policy that decides which browser origins may call the server. A request whose
        /// <c>Origin</c> the policy rejects receives HTTP 403 with no CORS headers, before preflight handling and
        /// authentication, including requests for the public Agent Card. The default allows requests without an
        /// <c>Origin</c> header and loopback origins. Setting null restores the default policy.
        /// </summary>
        public OriginPolicy OriginPolicy
        {
            get => _OriginPolicy;
            set => _OriginPolicy = value ?? new OriginPolicy();
        }

        /// <summary>
        /// Gets or sets whether only loopback clients are served. When true, a request whose remote address is
        /// not loopback receives HTTP 403. Default is true when the server is constructed with a loopback host
        /// name (<c>localhost</c>, <c>127.x.x.x</c>, or <c>::1</c>) and false otherwise. On Windows a
        /// <c>localhost</c> prefix is served on every interface and routed by the spoofable <c>Host</c> header,
        /// so this check is what keeps such a server local.
        /// </summary>
        public bool RestrictToLoopbackClients { get; set; }

        /// <summary>
        /// Gets or sets an optional validator for push notification webhook URLs, which replaces the built-in
        /// server-side request forgery (SSRF) protection. When null (the default), a webhook URL must be absolute
        /// <c>http</c> or <c>https</c> without user information, must not name <c>localhost</c> or a loopback,
        /// private, link-local, carrier-grade NAT, or multicast IP literal, and is re-checked when the server
        /// connects: if the host name resolves only to such addresses, delivery is refused (this also defeats DNS
        /// rebinding). Redirects are never followed and no proxy is used. When set, the delegate alone decides:
        /// return true to allow the URL (for example, an allowlist of webhook hosts, or loopback during local
        /// development); connect-time address checks are then skipped. A URL that fails validation is rejected
        /// with <see cref="A2AErrorCode.InvalidParams"/> when the configuration is created.
        /// </summary>
        public Func<Uri, bool>? PushNotificationUrlValidator
        {
            get => _PushNotificationUrlValidator;
            set => _PushNotificationUrlValidator = value;
        }

        /// <summary>
        /// Gets or sets the timeout for each push notification request, in milliseconds. Default is 10000 (the A2A
        /// specification recommends 10 to 30 seconds). Minimum 1000, maximum 300000.
        /// </summary>
        /// <exception cref="ArgumentOutOfRangeException">Thrown when the value is outside 1000 to 300000.</exception>
        public int PushNotificationTimeoutMs
        {
            get => _PushNotificationTimeoutMs;
            set
            {
                if (value < 1000 || value > 300000) throw new ArgumentOutOfRangeException(nameof(value), "The push notification timeout must be between 1000 and 300000 milliseconds.");
                _PushNotificationTimeoutMs = value;
            }
        }

        /// <summary>
        /// Gets or sets how many times a push notification is attempted before it is dropped. Failed attempts (a
        /// non-2xx response, a timeout, or a connection error) are retried with exponential backoff starting at 500
        /// milliseconds. Default is 3. Minimum 1, maximum 10.
        /// </summary>
        /// <exception cref="ArgumentOutOfRangeException">Thrown when the value is outside 1 to 10.</exception>
        public int PushNotificationMaxAttempts
        {
            get => _PushNotificationMaxAttempts;
            set
            {
                if (value < 1 || value > 10) throw new ArgumentOutOfRangeException(nameof(value), "The push notification attempt count must be between 1 and 10.");
                _PushNotificationMaxAttempts = value;
            }
        }

        /// <summary>
        /// Occurs when the server logs a diagnostic message, such as a rejected request or a background handler error.
        /// </summary>
        public event EventHandler<string>? Log;

        /// <summary>
        /// Initializes a new instance of the <see cref="A2AHttpServer"/> class. The server does not listen until
        /// <see cref="StartAsync"/> is called.
        /// </summary>
        /// <param name="hostname">The host name to listen on. Use <c>*</c> or <c>+</c> for all interfaces (requires admin rights or a URL ACL on Windows). A loopback name (<c>localhost</c>, <c>127.0.0.1</c>, <c>::1</c>) serves loopback clients only; see <see cref="RestrictToLoopbackClients"/>.</param>
        /// <param name="port">The port to listen on, from 0 to 65535.</param>
        /// <param name="agentCard">The public Agent Card. Must not be null.</param>
        /// <param name="handler">The agent handler. Default is null; register one later with <see cref="RegisterHandler"/>.</param>
        /// <param name="taskStore">The task store. Default is null, which uses a new <see cref="InMemoryA2ATaskStore"/>.</param>
        /// <param name="rpcPath">The JSON-RPC endpoint path. Default is <c>/a2a</c>.</param>
        /// <exception cref="ArgumentNullException">Thrown when <paramref name="hostname"/> is null, empty, or whitespace, or <paramref name="agentCard"/> is null.</exception>
        /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="port"/> is outside 0 to 65535.</exception>
        public A2AHttpServer(string hostname, int port, AgentCard agentCard, IA2AAgentHandler? handler = null, IA2ATaskStore? taskStore = null, string rpcPath = "/a2a")
        {
            if (String.IsNullOrWhiteSpace(hostname)) throw new ArgumentNullException(nameof(hostname));
            if (port < 0 || port > 65535) throw new ArgumentOutOfRangeException(nameof(port));

            _Hostname = hostname;
            _Port = port;
            RestrictToLoopbackClients = LoopbackAddresses.IsLoopbackHostname(hostname);
            _RpcPath = NormalizePath(rpcPath);
            AgentCard = agentCard ?? throw new ArgumentNullException(nameof(agentCard));
            Handler = handler;
            _TaskStore = taskStore ?? new InMemoryA2ATaskStore();
            _PushClient = new HttpClient(new SocketsHttpHandler
            {
                AllowAutoRedirect = false,
                UseProxy = false,
                ConnectCallback = ConnectToWebhookAsync
            })
            {
                Timeout = System.Threading.Timeout.InfiniteTimeSpan
            };
        }

        /// <summary>
        /// Sets or replaces the agent handler. Requests already in progress keep the handler they started with.
        /// </summary>
        /// <param name="handler">The agent handler.</param>
        /// <exception cref="ArgumentNullException">Thrown when <paramref name="handler"/> is null.</exception>
        public void RegisterHandler(IA2AAgentHandler handler)
        {
            Handler = handler ?? throw new ArgumentNullException(nameof(handler));
        }

        /// <summary>
        /// Starts listening and returns once the listener is running; requests are then accepted on a background
        /// loop until <see cref="Stop"/> or <see cref="Dispose"/> is called or <paramref name="token"/> is canceled.
        /// After <see cref="Stop"/> the server can be started again.
        /// </summary>
        /// <param name="token">Cancellation token that stops the server when canceled.</param>
        /// <returns>A task that completes when the listener has started.</returns>
        /// <exception cref="InvalidOperationException">Thrown when the server is already running.</exception>
        /// <exception cref="ObjectDisposedException">Thrown when the server has been disposed.</exception>
        /// <exception cref="HttpListenerException">Thrown when the listener cannot bind the prefix (for example the port is in use, or a non-loopback prefix lacks permission).</exception>
        public async Task StartAsync(CancellationToken token = default)
        {
            lock (_LifecycleLock)
            {
                if (_IsDisposed) throw new ObjectDisposedException(nameof(A2AHttpServer));
                if (_Listener != null)
                {
                    throw new InvalidOperationException("Server is already started.");
                }

                HttpListener listener = new HttpListener();
                string prefixHost = _Hostname == "*" ? "+" : _Hostname;
                listener.Prefixes.Add($"http://{prefixHost}:{_Port}/");
                listener.Start();

                _TokenSource = CancellationTokenSource.CreateLinkedTokenSource(token);
                _Listener = listener;
                CancellationToken loopToken = _TokenSource.Token;
                _ListenTask = Task.Run(() => ListenLoopAsync(listener, loopToken));
            }

            await Task.Yield();
        }

        /// <summary>
        /// Stops accepting requests, cancels in-flight request processing, and waits up to five seconds for the
        /// accept loop to finish. The server can then be started again with <see cref="StartAsync"/>. Safe to call
        /// more than once. Pending push notifications continue until <see cref="Dispose"/>.
        /// </summary>
        public void Stop()
        {
            HttpListener? listener;
            CancellationTokenSource? tokenSource;
            Task? listenTask;
            lock (_LifecycleLock)
            {
                listener = _Listener;
                tokenSource = _TokenSource;
                listenTask = _ListenTask;
                _Listener = null;
                _TokenSource = null;
                _ListenTask = null;
            }

            try
            {
                tokenSource?.Cancel();
            }
            catch (ObjectDisposedException)
            {
            }

            try
            {
                listener?.Stop();
                listener?.Close();
            }
            catch
            {
            }

            try
            {
                listenTask?.Wait(TimeSpan.FromSeconds(5));
            }
            catch
            {
            }

            tokenSource?.Dispose();
        }

        /// <summary>
        /// Stops the server and releases the listener. Safe to call more than once.
        /// </summary>
        public void Dispose()
        {
            if (_IsDisposed)
            {
                return;
            }

            Stop();
            _IsDisposed = true;
            _PushShutdown.Cancel();
            _PushClient.Dispose();
            _PushShutdown.Dispose();
        }

        private async Task ListenLoopAsync(HttpListener listener, CancellationToken token)
        {
            while (!token.IsCancellationRequested && listener.IsListening)
            {
                try
                {
                    HttpListenerContext context = await listener.GetContextAsync().ConfigureAwait(false);
                    _ = Task.Run(() => HandleRequestAsync(context, token));
                }
                catch (Exception ex) when (token.IsCancellationRequested || ex is HttpListenerException || ex is ObjectDisposedException)
                {
                    break;
                }
            }
        }

        private async Task HandleRequestAsync(HttpListenerContext context, CancellationToken token)
        {
            try
            {
                if (!HttpAccessGuard.IsRemoteAllowed(context.Request, RestrictToLoopbackClients))
                {
                    Log?.Invoke(this, $"Rejected remote client {context.Request.RemoteEndPoint}: the server accepts loopback clients only");
                    await HttpAccessGuard.RejectAsync(context, 403, "Remote connections are not allowed.", token).ConfigureAwait(false);
                    return;
                }

                string? origin = HttpAccessGuard.GetOrigin(context.Request);
                if (!_OriginPolicy.IsAllowed(origin))
                {
                    Log?.Invoke(this, $"Rejected request from disallowed origin '{origin}'");
                    await HttpAccessGuard.RejectAsync(context, 403, "Origin not allowed.", token).ConfigureAwait(false);
                    return;
                }

                AddCors(context);
                if (context.Request.HttpMethod == "OPTIONS")
                {
                    context.Response.StatusCode = 204;
                    context.Response.Close();
                    return;
                }

                AuthenticationResult? caller = null;
                if (AuthenticationHandler != null && !IsPublicAgentCardRequest(context.Request))
                {
                    AuthenticationResult auth = await AuthenticationHandler(context.Request).ConfigureAwait(false);
                    if (!auth.IsAuthenticated)
                    {
                        foreach (KeyValuePair<string, string> header in auth.Headers)
                        {
                            if (String.IsNullOrEmpty(header.Key) || header.Value == null) continue;
                            context.Response.AddHeader(header.Key, header.Value);
                        }

                        await SendTextAsync(context, auth.StatusCode, auth.ErrorMessage ?? "Unauthorized", token).ConfigureAwait(false);
                        return;
                    }

                    caller = auth;
                }

                // Make the authenticated caller ambient so it is copied onto the A2ARequestContext built
                // for the agent handler. Push(null) is a no-op-then-restore for unauthenticated paths.
                using (A2ACallerContext.Push(caller))
                {
                    string path = context.Request.Url?.AbsolutePath ?? "/";

                    if (context.Request.HttpMethod == "GET" && StringComparer.OrdinalIgnoreCase.Equals(path, A2AProtocol.AgentCardPath))
                    {
                        await SendJsonAsync(context, AgentCard, token).ConfigureAwait(false);
                        return;
                    }

                    if (context.Request.HttpMethod == "GET" && StringComparer.OrdinalIgnoreCase.Equals(path, A2AProtocol.ExtendedAgentCardPath))
                    {
                        AgentCard extended = GetExtendedAgentCard();
                        await SendJsonAsync(context, extended, token).ConfigureAwait(false);
                        return;
                    }

                    if (StringComparer.OrdinalIgnoreCase.Equals(path, _RpcPath))
                    {
                        await HandleJsonRpcAsync(context, token).ConfigureAwait(false);
                        return;
                    }

                    if (await TryHandleRestAsync(context, path, token).ConfigureAwait(false))
                    {
                        return;
                    }

                    await SendTextAsync(context, 404, "Not found", token).ConfigureAwait(false);
                }
            }
            catch (Exception ex)
            {
                LogMessage($"A2A request error: {ex.Message}");
                if (context.Response.OutputStream.CanWrite)
                {
                    await SendJsonErrorAsync(context, ex, null, token).ConfigureAwait(false);
                }
            }
        }

        private async Task HandleJsonRpcAsync(HttpListenerContext context, CancellationToken token)
        {
            if (context.Request.HttpMethod != "POST")
            {
                await SendTextAsync(context, 405, "Method not allowed", token).ConfigureAwait(false);
                return;
            }

            string body = await ReadBodyAsync(context.Request).ConfigureAwait(false);
            JsonRpcRequest? request;
            try
            {
                request = JsonSerializer.Deserialize<JsonRpcRequest>(body, A2AJson.DefaultOptions);
            }
            catch (JsonException)
            {
                await SendJsonRpcErrorAsync(context, new A2AProtocolException(A2AErrorCode.ParseError, "Parse error"), null, token).ConfigureAwait(false);
                return;
            }

            if (request == null || String.IsNullOrWhiteSpace(request.Method))
            {
                await SendJsonRpcErrorAsync(context, new A2AProtocolException(A2AErrorCode.InvalidRequest, "Invalid JSON-RPC request."), request?.Id, token).ConfigureAwait(false);
                return;
            }

            if (!A2AProtocol.IsValidMethod(request.Method))
            {
                await SendJsonRpcErrorAsync(context, new A2AProtocolException(A2AErrorCode.MethodNotFound, $"Method '{request.Method}' was not found."), request.Id, token).ConfigureAwait(false);
                return;
            }

            if (A2AProtocol.IsStreamingMethod(request.Method))
            {
                context.Response.StatusCode = 200;
                context.Response.ContentType = "text/event-stream";
                context.Response.SendChunked = true;
                await context.Response.OutputStream.WriteAsync(_SsePrelude, 0, _SsePrelude.Length, token).ConfigureAwait(false);
                await context.Response.OutputStream.FlushAsync(token).ConfigureAwait(false);

                try
                {
                    await foreach (StreamResponse item in InvokeStreamingMethodAsync(request.Method, request.Params, token).ConfigureAwait(false))
                    {
                        JsonRpcResponse response = new JsonRpcResponse { Id = request.Id, Result = item };
                        await SendSseJsonAsync(context.Response, response, token).ConfigureAwait(false);
                    }
                }
                catch (Exception ex)
                {
                    JsonRpcResponse response = BuildErrorResponse(ex, request.Id);
                    await SendSseJsonAsync(context.Response, response, token).ConfigureAwait(false);
                }
                finally
                {
                    context.Response.Close();
                }

                return;
            }

            try
            {
                object? result = await InvokeMethodAsync(request.Method, request.Params, token).ConfigureAwait(false);
                JsonRpcResponse response = new JsonRpcResponse { Id = request.Id, Result = result };
                await SendJsonAsync(context, response, token).ConfigureAwait(false);
            }
            catch (Exception ex)
            {
                await SendJsonRpcErrorAsync(context, ex, request.Id, token).ConfigureAwait(false);
            }
        }

        private async Task<bool> TryHandleRestAsync(HttpListenerContext context, string path, CancellationToken token)
        {
            string[] segments = path.Trim('/').Split('/', StringSplitOptions.RemoveEmptyEntries);

            if (context.Request.HttpMethod == "POST" && path == "/message:send")
            {
                SendMessageRequest request = await ReadJsonAsync<SendMessageRequest>(context.Request).ConfigureAwait(false);
                await SendJsonAsync(context, await SendMessageAsync(request, false, token).ConfigureAwait(false), token).ConfigureAwait(false);
                return true;
            }

            if (context.Request.HttpMethod == "POST" && path == "/message:stream")
            {
                SendMessageRequest request = await ReadJsonAsync<SendMessageRequest>(context.Request).ConfigureAwait(false);
                context.Response.StatusCode = 200;
                context.Response.ContentType = "text/event-stream";
                context.Response.SendChunked = true;
                await context.Response.OutputStream.WriteAsync(_SsePrelude, 0, _SsePrelude.Length, token).ConfigureAwait(false);
                await foreach (StreamResponse item in SendStreamingMessageAsync(request, token).ConfigureAwait(false))
                {
                    await SendSseJsonAsync(context.Response, item, token).ConfigureAwait(false);
                }
                context.Response.Close();
                return true;
            }

            if (segments.Length == 1 && segments[0] == "tasks" && context.Request.HttpMethod == "GET")
            {
                ListTasksRequest request = new ListTasksRequest
                {
                    ContextId = context.Request.QueryString["contextId"],
                    Status = TryParseTaskState(context.Request.QueryString["status"]),
                    PageToken = context.Request.QueryString["pageToken"],
                    PageSize = TryParseInt(context.Request.QueryString["pageSize"]),
                    HistoryLength = TryParseInt(context.Request.QueryString["historyLength"]),
                    StatusTimestampAfter = TryParseDateTimeOffset(context.Request.QueryString["statusTimestampAfter"]),
                    IncludeArtifacts = TryParseBool(context.Request.QueryString["includeArtifacts"])
                };
                await SendJsonAsync(context, await ListTasksAsync(request, token).ConfigureAwait(false), token).ConfigureAwait(false);
                return true;
            }

            if (segments.Length >= 2 && segments[0] == "tasks")
            {
                string taskId = Uri.UnescapeDataString(segments[1]);
                if (segments.Length == 2 && context.Request.HttpMethod == "GET")
                {
                    GetTaskRequest request = new GetTaskRequest
                    {
                        Id = taskId,
                        HistoryLength = TryParseInt(context.Request.QueryString["historyLength"])
                    };
                    await SendJsonAsync(context, await GetTaskAsync(request, token).ConfigureAwait(false), token).ConfigureAwait(false);
                    return true;
                }

                if (segments.Length == 2 && segments[1].EndsWith(":cancel", StringComparison.Ordinal))
                {
                    string id = Uri.UnescapeDataString(segments[1].Substring(0, segments[1].Length - ":cancel".Length));
                    await SendJsonAsync(context, await CancelTaskAsync(new CancelTaskRequest { Id = id }, token).ConfigureAwait(false), token).ConfigureAwait(false);
                    return true;
                }

                if (segments.Length == 2 && segments[1].EndsWith(":subscribe", StringComparison.Ordinal))
                {
                    string id = Uri.UnescapeDataString(segments[1].Substring(0, segments[1].Length - ":subscribe".Length));
                    context.Response.StatusCode = 200;
                    context.Response.ContentType = "text/event-stream";
                    context.Response.SendChunked = true;
                    await context.Response.OutputStream.WriteAsync(_SsePrelude, 0, _SsePrelude.Length, token).ConfigureAwait(false);
                    await foreach (StreamResponse item in SubscribeToTaskAsync(new SubscribeToTaskRequest { Id = id }, token).ConfigureAwait(false))
                    {
                        await SendSseJsonAsync(context.Response, item, token).ConfigureAwait(false);
                    }
                    context.Response.Close();
                    return true;
                }

                if (segments.Length >= 3 && segments[2] == "pushNotificationConfigs")
                {
                    if (segments.Length == 3 && context.Request.HttpMethod == "POST")
                    {
                        CreateTaskPushNotificationConfigRequest request = await ReadPushNotificationConfigRequestAsync(context.Request).ConfigureAwait(false);
                        request.TaskId = taskId;
                        await SendJsonAsync(context, await CreateTaskPushNotificationConfigAsync(request, token).ConfigureAwait(false), token).ConfigureAwait(false);
                        return true;
                    }

                    if (segments.Length == 3 && context.Request.HttpMethod == "GET")
                    {
                        await SendJsonAsync(context, await ListTaskPushNotificationConfigAsync(new ListTaskPushNotificationConfigRequest { TaskId = taskId }, token).ConfigureAwait(false), token).ConfigureAwait(false);
                        return true;
                    }

                    if (segments.Length == 4)
                    {
                        string configId = Uri.UnescapeDataString(segments[3]);
                        if (context.Request.HttpMethod == "GET")
                        {
                            await SendJsonAsync(context, await GetTaskPushNotificationConfigAsync(new GetTaskPushNotificationConfigRequest { TaskId = taskId, ConfigId = configId }, token).ConfigureAwait(false), token).ConfigureAwait(false);
                            return true;
                        }

                        if (context.Request.HttpMethod == "DELETE")
                        {
                            await DeleteTaskPushNotificationConfigAsync(new DeleteTaskPushNotificationConfigRequest { TaskId = taskId, ConfigId = configId }, token).ConfigureAwait(false);
                            await SendJsonAsync(context, new { }, token).ConfigureAwait(false);
                            return true;
                        }
                    }
                }
            }

            return false;
        }

        private async Task<object?> InvokeMethodAsync(string method, object? parameters, CancellationToken token)
        {
            return method switch
            {
                A2AProtocol.SendMessage => await SendMessageAsync(DeserializeParams<SendMessageRequest>(parameters), false, token).ConfigureAwait(false),
                A2AProtocol.GetTask => await GetTaskAsync(DeserializeParams<GetTaskRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.ListTasks => await ListTasksAsync(DeserializeParams<ListTasksRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.CancelTask => await CancelTaskAsync(DeserializeParams<CancelTaskRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.CreateTaskPushNotificationConfig => await CreateTaskPushNotificationConfigAsync(DeserializeParams<CreateTaskPushNotificationConfigRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.GetTaskPushNotificationConfig => await GetTaskPushNotificationConfigAsync(DeserializeParams<GetTaskPushNotificationConfigRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.ListTaskPushNotificationConfig => await ListTaskPushNotificationConfigAsync(DeserializeParams<ListTaskPushNotificationConfigRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.ListTaskPushNotificationConfigLegacy => await ListTaskPushNotificationConfigAsync(DeserializeParams<ListTaskPushNotificationConfigRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.DeleteTaskPushNotificationConfig => await DeleteForRpcAsync(DeserializeParams<DeleteTaskPushNotificationConfigRequest>(parameters), token).ConfigureAwait(false),
                A2AProtocol.GetExtendedAgentCard => GetExtendedAgentCard(),
                _ => throw new A2AProtocolException(A2AErrorCode.MethodNotFound, $"Method '{method}' was not found.")
            };
        }

        private async IAsyncEnumerable<StreamResponse> InvokeStreamingMethodAsync(string method, object? parameters, [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken token)
        {
            if (method == A2AProtocol.SendStreamingMessage)
            {
                await foreach (StreamResponse item in SendStreamingMessageAsync(DeserializeParams<SendMessageRequest>(parameters), token).ConfigureAwait(false))
                {
                    yield return item;
                }
                yield break;
            }

            if (method == A2AProtocol.SubscribeToTask)
            {
                await foreach (StreamResponse item in SubscribeToTaskAsync(DeserializeParams<SubscribeToTaskRequest>(parameters), token).ConfigureAwait(false))
                {
                    yield return item;
                }
                yield break;
            }

            throw new A2AProtocolException(A2AErrorCode.MethodNotFound, $"Method '{method}' was not found.");
        }

        /// <summary>
        /// Handles <c>SendMessage</c>: resolves or creates the task, runs the agent handler, applies its events to
        /// the task store, and returns the first event as a task (refreshed from the store) or a message. With
        /// <c>configuration.returnImmediately</c> (and <paramref name="streaming"/> false) the task is saved as
        /// submitted and returned at once while the handler runs in the background. The request's message has its
        /// <c>taskId</c> and <c>contextId</c> filled in.
        /// </summary>
        /// <param name="request">The request. Must contain a message.</param>
        /// <param name="streaming">True when called for a streaming request; recorded on <see cref="A2ARequestContext.StreamingResponse"/>.</param>
        /// <param name="token">Cancellation token for the request.</param>
        /// <returns>The response, carrying either a task or a message.</returns>
        /// <remarks>
        /// When <see cref="SendMessageConfiguration.PushNotificationConfig"/> is set, it is registered for the task before
        /// the handler runs, so every event of the task is delivered to that webhook.
        /// </remarks>
        /// <exception cref="A2AProtocolException">Thrown with <see cref="A2AErrorCode.InvalidParams"/> when the request or message is missing or the push notification URL is not allowed, <see cref="A2AErrorCode.TaskNotFound"/> when the message references an unknown task, <see cref="A2AErrorCode.UnsupportedOperation"/> when the task is terminal, <see cref="A2AErrorCode.PushNotificationNotSupported"/> when a push notification configuration is supplied but the Agent Card does not advertise push notifications, <see cref="A2AErrorCode.InternalError"/> when no handler is registered, or <see cref="A2AErrorCode.InvalidAgentResponse"/> when the handler produces no events.</exception>
        public async Task<SendMessageResponse> SendMessageAsync(SendMessageRequest request, bool streaming, CancellationToken token = default)
        {
            A2ARequestContext context = await ResolveContextAsync(request, streaming, token).ConfigureAwait(false);
            IA2AAgentHandler handler = Handler ?? throw new A2AProtocolException(A2AErrorCode.InternalError, "No A2A handler is registered.");
            RegisterMessagePushConfig(context);

            if (!streaming && context.Configuration?.ReturnImmediately == true)
            {
                AgentTask accepted = await SaveAcceptedTaskAsync(context, token).ConfigureAwait(false);
                CancellationToken backgroundToken = _TokenSource?.Token ?? token;
                _ = Task.Run(() => ExecuteHandlerAndApplyEventsAsync(handler, context, backgroundToken), backgroundToken);
                return new SendMessageResponse { Task = accepted };
            }

            A2AAgentEventQueue queue = new A2AAgentEventQueue();

            Task handlerTask = Task.Run(async () =>
            {
                try
                {
                    await handler.ExecuteAsync(context, queue, token).ConfigureAwait(false);
                }
                finally
                {
                    queue.Complete();
                }
            }, token);

            SendMessageResponse? first = null;
            await foreach (StreamResponse item in queue.ReadAllAsync(token).ConfigureAwait(false))
            {
                await ApplyEventAsync(item, context, token).ConfigureAwait(false);
                if (first == null)
                {
                    if (item.Task != null) first = new SendMessageResponse { Task = item.Task };
                    else if (item.Message != null) first = new SendMessageResponse { Message = item.Message };
                    else if (item.StatusUpdate != null || item.ArtifactUpdate != null)
                    {
                        AgentTask? projected = await _TaskStore.GetTaskAsync(context.TaskId, token).ConfigureAwait(false);
                        if (projected != null)
                        {
                            first = new SendMessageResponse { Task = projected };
                        }
                    }
                }
            }

            await handlerTask.ConfigureAwait(false);

            if (first?.Task != null)
            {
                first.Task = await _TaskStore.GetTaskAsync(context.TaskId, token).ConfigureAwait(false) ?? first.Task;
            }

            return first ?? throw new A2AProtocolException(A2AErrorCode.InvalidAgentResponse, "Agent handler did not produce a response.");
        }

        private async Task ExecuteHandlerAndApplyEventsAsync(IA2AAgentHandler handler, A2ARequestContext context, CancellationToken token)
        {
            A2AAgentEventQueue queue = new A2AAgentEventQueue();
            Task handlerTask = Task.Run(async () =>
            {
                try
                {
                    await handler.ExecuteAsync(context, queue, token).ConfigureAwait(false);
                }
                finally
                {
                    queue.Complete();
                }
            }, token);

            try
            {
                await foreach (StreamResponse item in queue.ReadAllAsync(token).ConfigureAwait(false))
                {
                    await ApplyEventAsync(item, context, token).ConfigureAwait(false);
                }

                await handlerTask.ConfigureAwait(false);
            }
            catch (Exception ex) when (!(ex is OperationCanceledException && token.IsCancellationRequested))
            {
                LogMessage($"A2A background handler error: {ex.Message}");
                await ApplyEventAsync(new StreamResponse
                {
                    StatusUpdate = new TaskStatusUpdateEvent
                    {
                        TaskId = context.TaskId,
                        ContextId = context.ContextId,
                        Status = new TaskStatus
                        {
                            State = TaskState.Failed,
                            Timestamp = DateTimeOffset.UtcNow,
                            Message = new Message
                            {
                                Role = Role.Agent,
                                MessageId = Guid.NewGuid().ToString("N"),
                                TaskId = context.TaskId,
                                ContextId = context.ContextId,
                                Parts = new List<Part> { Part.FromText("Agent handler failed.") }
                            }
                        }
                    }
                }, context, CancellationToken.None).ConfigureAwait(false);
            }
        }

        private async Task<AgentTask> SaveAcceptedTaskAsync(A2ARequestContext context, CancellationToken token)
        {
            AgentTask task = context.ExistingTask?.Clone() ?? new AgentTask
            {
                Id = context.TaskId,
                ContextId = context.ContextId,
                History = new List<Message>(),
                Artifacts = new List<Artifact>()
            };

            task.Status = new TaskStatus
            {
                State = TaskState.Submitted,
                Timestamp = DateTimeOffset.UtcNow
            };
            task.History ??= new List<Message>();
            if (!task.History.Any(message => message.MessageId == context.Message.MessageId))
            {
                task.History.Add(context.Message);
            }

            await _TaskStore.SaveTaskAsync(task.Id, task, token).ConfigureAwait(false);
            return task.WithHistoryTrimmedTo(context.Configuration?.HistoryLength);
        }

        /// <summary>
        /// Handles <c>SendStreamingMessage</c>: runs the agent handler and yields each event as it is applied to
        /// the task store.
        /// </summary>
        /// <param name="request">The request. Must contain a message.</param>
        /// <param name="token">Cancellation token for the stream.</param>
        /// <returns>The agent's events, in order.</returns>
        /// <exception cref="A2AProtocolException">Thrown with <see cref="A2AErrorCode.InvalidParams"/>, <see cref="A2AErrorCode.TaskNotFound"/>, <see cref="A2AErrorCode.UnsupportedOperation"/>, or <see cref="A2AErrorCode.InternalError"/> under the same conditions as <see cref="SendMessageAsync"/>.</exception>
        public async IAsyncEnumerable<StreamResponse> SendStreamingMessageAsync(SendMessageRequest request, [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken token = default)
        {
            A2ARequestContext context = await ResolveContextAsync(request, true, token).ConfigureAwait(false);
            A2AAgentEventQueue queue = new A2AAgentEventQueue();
            IA2AAgentHandler handler = Handler ?? throw new A2AProtocolException(A2AErrorCode.InternalError, "No A2A handler is registered.");
            RegisterMessagePushConfig(context);

            Task handlerTask = Task.Run(async () =>
            {
                try
                {
                    await handler.ExecuteAsync(context, queue, token).ConfigureAwait(false);
                }
                finally
                {
                    queue.Complete();
                }
            }, token);

            await foreach (StreamResponse item in queue.ReadAllAsync(token).ConfigureAwait(false))
            {
                await ApplyEventAsync(item, context, token).ConfigureAwait(false);
                yield return item;
            }

            await handlerTask.ConfigureAwait(false);
        }

