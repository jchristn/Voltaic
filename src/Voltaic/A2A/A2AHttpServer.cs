        /// Handles <c>CreateTaskPushNotificationConfig</c>: stores a push notification configuration for a task,
        /// replacing any with the same configuration ID. The ID is the request's, the config's, or a new one.
        /// Configurations are held in memory.
        /// </summary>
        /// <param name="request">The request.</param>
        /// <param name="token">Cancellation token for the request.</param>
        /// <returns>The stored configuration.</returns>
        /// <exception cref="A2AProtocolException">Thrown with <see cref="A2AErrorCode.PushNotificationNotSupported"/> when the Agent Card does not advertise push notifications, <see cref="A2AErrorCode.InvalidParams"/> when the task ID is missing or the webhook URL is missing or not allowed (see <see cref="PushNotificationUrlValidator"/>), or <see cref="A2AErrorCode.TaskNotFound"/> when no task has the ID.</exception>
        public async Task<TaskPushNotificationConfig> CreateTaskPushNotificationConfigAsync(CreateTaskPushNotificationConfigRequest request, CancellationToken token = default)
        {
            EnsurePushNotificationsSupported();
            if (request == null) throw A2AProtocolException.InvalidParams("CreateTaskPushNotificationConfig requires params.");
            if (String.IsNullOrWhiteSpace(request.TaskId)) throw A2AProtocolException.InvalidParams("TaskId is required.");
            await EnsureTaskExistsAsync(request.TaskId, token).ConfigureAwait(false);

