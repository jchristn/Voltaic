        private void RegisterMessagePushConfig(A2ARequestContext context)
        {
            PushNotificationConfig? pushConfig = context.Configuration?.PushNotificationConfig;
            if (pushConfig == null) return;

            EnsurePushNotificationsSupported();
            StorePushConfig(context.TaskId, pushConfig.Id ?? Guid.NewGuid().ToString("N"), context.SendMessageRequest?.Tenant, pushConfig);
        }

        private TaskPushNotificationConfig StorePushConfig(string taskId, string configId, string? tenant, PushNotificationConfig? pushConfig)
        {
            if (pushConfig == null || String.IsNullOrWhiteSpace(pushConfig.Url)) throw A2AProtocolException.InvalidParams("A push notification configuration requires a url.");
            ValidateWebhookUrl(pushConfig.Url);

            TaskPushNotificationConfig config = new TaskPushNotificationConfig
            {
                Id = configId,
                TaskId = taskId,
                Tenant = tenant,
                PushNotificationConfig = pushConfig
            };
            _PushConfigs.GetOrAdd(taskId, _ => new ConcurrentDictionary<string, TaskPushNotificationConfig>(StringComparer.Ordinal))[configId] = config;
            return config;
        }

        private void ValidateWebhookUrl(string url)
        {
            if (!Uri.TryCreate(url, UriKind.Absolute, out Uri? uri))
            {
                throw A2AProtocolException.InvalidParams("The push notification url must be an absolute URL.");
            }

            Func<Uri, bool>? validator = _PushNotificationUrlValidator;
            if (validator != null)
            {
                bool allowed;
                try
                {
                    allowed = validator(uri);
                }
                catch
                {
                    allowed = false;
                }

                if (!allowed) throw A2AProtocolException.InvalidParams("The push notification url is not allowed by this server.");
                return;
            }

            string? reason = A2AWebhookAddressPolicy.ValidateUrl(uri);
            if (reason != null) throw A2AProtocolException.InvalidParams(reason);
        }

        private void QueuePushNotifications(string taskId, StreamResponse response)
        {
            if (!_PushConfigs.TryGetValue(taskId, out ConcurrentDictionary<string, TaskPushNotificationConfig>? configs) || configs.IsEmpty)
            {
                return;
            }

            string payload = JsonSerializer.Serialize(response, A2AJson.DefaultOptions);
            foreach (TaskPushNotificationConfig config in configs.Values)
            {
                // Deliveries to one webhook are sent in order: each waits for the previous one to finish.
                string key = taskId + "\n" + config.Id;
                lock (_PushLock)
                {
                    Task previous = _PushTails.TryGetValue(key, out Task? tail) ? tail : Task.CompletedTask;
                    _PushTails[key] = previous.ContinueWith(
                        _ => DeliverPushNotificationAsync(config, payload),
                        CancellationToken.None,
                        TaskContinuationOptions.None,
                        TaskScheduler.Default).Unwrap();
                }
            }
        }

        private async Task DeliverPushNotificationAsync(TaskPushNotificationConfig config, string payload)
        {
            PushNotificationConfig target = config.PushNotificationConfig;
            if (!Uri.TryCreate(target.Url, UriKind.Absolute, out Uri? uri)) return;

            for (int attempt = 1; attempt <= _PushNotificationMaxAttempts; attempt++)
            {
                if (_PushShutdown.IsCancellationRequested) return;

                try
                {
                    using CancellationTokenSource timeout = CancellationTokenSource.CreateLinkedTokenSource(_PushShutdown.Token);
                    timeout.CancelAfter(_PushNotificationTimeoutMs);

                    using HttpRequestMessage request = new HttpRequestMessage(HttpMethod.Post, uri)
                    {
                        Content = new StringContent(payload, Encoding.UTF8, "application/a2a+json")
                    };
                    request.Headers.TryAddWithoutValidation(A2AProtocol.VersionHeader, A2AProtocol.ProtocolVersion);

                    AuthenticationInfo? authentication = target.Authentication;
                    if (authentication != null && !String.IsNullOrEmpty(authentication.Credentials))
                    {
                        string scheme = String.IsNullOrWhiteSpace(authentication.Scheme) ? "Bearer" : authentication.Scheme;
                        request.Headers.TryAddWithoutValidation("Authorization", $"{scheme} {authentication.Credentials}");
                    }

                    if (!String.IsNullOrEmpty(target.Token))
                    {
                        request.Headers.TryAddWithoutValidation(A2AProtocol.NotificationTokenHeader, target.Token);
                    }

                    using HttpResponseMessage response = await _PushClient.SendAsync(request, timeout.Token).ConfigureAwait(false);
                    if (response.IsSuccessStatusCode) return;

                    LogMessage($"Push notification to {uri.GetLeftPart(UriPartial.Path)} for task {config.TaskId} returned HTTP {(int)response.StatusCode} (attempt {attempt} of {_PushNotificationMaxAttempts})");
                }
                catch (Exception ex) when (!_PushShutdown.IsCancellationRequested)
                {
                    LogMessage($"Push notification to {uri.GetLeftPart(UriPartial.Path)} for task {config.TaskId} failed: {ex.Message} (attempt {attempt} of {_PushNotificationMaxAttempts})");
                }
                catch
                {
                    return;
                }

                if (attempt < _PushNotificationMaxAttempts)
                {
                    try
                    {
                        await Task.Delay(TimeSpan.FromMilliseconds(500 * Math.Pow(2, attempt - 1)), _PushShutdown.Token).ConfigureAwait(false);
                    }
                    catch (OperationCanceledException)
                    {
                        return;
                    }
                }
            }
        }

        private async ValueTask<Stream> ConnectToWebhookAsync(SocketsHttpConnectionContext context, CancellationToken token)
        {
            // Resolve and connect here so the address actually used is the one that was checked, which defeats
            // DNS rebinding. A custom validator replaces the built-in address policy entirely.
            bool enforcePolicy = _PushNotificationUrlValidator == null;
            IPAddress[] addresses = await Dns.GetHostAddressesAsync(context.DnsEndPoint.Host, token).ConfigureAwait(false);
            List<IPAddress> candidates = addresses.Where(address => !enforcePolicy || A2AWebhookAddressPolicy.IsPublic(address)).ToList();
            if (candidates.Count == 0)
            {
                throw new HttpRequestException($"Webhook host '{context.DnsEndPoint.Host}' resolves only to addresses this server does not call (loopback, private, or link-local).");
            }

            Exception? last = null;
            foreach (IPAddress address in candidates)
            {
                Socket socket = new Socket(address.AddressFamily, SocketType.Stream, ProtocolType.Tcp) { NoDelay = true };
                try
                {
                    await socket.ConnectAsync(new IPEndPoint(address, context.DnsEndPoint.Port), token).ConfigureAwait(false);
                    return new NetworkStream(socket, ownsSocket: true);
                }
                catch (Exception ex)
                {
                    socket.Dispose();
                    last = ex;
                }
            }

            throw new HttpRequestException($"Could not connect to webhook host '{context.DnsEndPoint.Host}'.", last);
        }

        private void EnsurePushNotificationsSupported()
        {
            if (AgentCard.Capabilities.PushNotifications != true)
            {
                throw new A2AProtocolException(A2AErrorCode.PushNotificationNotSupported, "Push notifications are not supported.");
            }
        }

        private static T DeserializeParams<T>(object? parameters) where T : new()
        {
            if (parameters == null)
            {
                return new T();
            }

            string json = JsonSerializer.Serialize(parameters, A2AJson.DefaultOptions);
            return JsonSerializer.Deserialize<T>(json, A2AJson.DefaultOptions) ?? new T();
        }

        private static async Task<T> ReadJsonAsync<T>(HttpListenerRequest request) where T : new()
        {
            string body = await ReadBodyAsync(request).ConfigureAwait(false);
            if (String.IsNullOrWhiteSpace(body))
            {
                return new T();
            }

            return JsonSerializer.Deserialize<T>(body, A2AJson.DefaultOptions) ?? new T();
        }

        private static async Task<CreateTaskPushNotificationConfigRequest> ReadPushNotificationConfigRequestAsync(HttpListenerRequest request)
        {
            string body = await ReadBodyAsync(request).ConfigureAwait(false);
            if (String.IsNullOrWhiteSpace(body))
            {
                return new CreateTaskPushNotificationConfigRequest();
            }

            Dictionary<string, object?>? fields = JsonSerializer.Deserialize<Dictionary<string, object?>>(body, A2AJson.DefaultOptions);
            if (fields != null && fields.ContainsKey("config"))
            {
                return JsonSerializer.Deserialize<CreateTaskPushNotificationConfigRequest>(body, A2AJson.DefaultOptions)
                    ?? new CreateTaskPushNotificationConfigRequest();
            }

            PushNotificationConfig? config = JsonSerializer.Deserialize<PushNotificationConfig>(body, A2AJson.DefaultOptions);
            return new CreateTaskPushNotificationConfigRequest
            {
                ConfigId = config?.Id ?? string.Empty,
                Config = config ?? new PushNotificationConfig()
            };
        }

        private static async Task<string> ReadBodyAsync(HttpListenerRequest request)
        {
            using StreamReader reader = new StreamReader(request.InputStream, request.ContentEncoding ?? Encoding.UTF8);
            return await reader.ReadToEndAsync().ConfigureAwait(false);
        }

        // Writes an error for the HTTP+JSON (REST) binding, with the HTTP status the A2A specification maps the error to (404 for task not found, 500 for internal and invalid-agent-response errors, 400 otherwise).
        private async Task SendJsonErrorAsync(HttpListenerContext context, Exception ex, object? id, CancellationToken token)
        {
            // HTTP+JSON errors use the google.rpc.Status shape with an ErrorInfo reason (A2A v1.0 section 11.6).
            JsonRpcError error = BuildErrorResponse(ex, id).Error!;
            A2AErrorCode code = Enum.IsDefined(typeof(A2AErrorCode), error.Code) ? (A2AErrorCode)error.Code : A2AErrorCode.InternalError;
            context.Response.StatusCode = A2ARestErrors.HttpStatus(code);
            await SendJsonAsync(context, A2ARestErrors.Body(code, error.Message), token).ConfigureAwait(false);
        }

        // Writes an error for the JSON-RPC binding. JSON-RPC carries the error in the response body, so the HTTP status is 200, as JSON-RPC-over-HTTP clients expect.
        private async Task SendJsonRpcErrorAsync(HttpListenerContext context, Exception ex, object? id, CancellationToken token)
        {
            context.Response.StatusCode = 200;
            await SendJsonAsync(context, BuildErrorResponse(ex, id), token).ConfigureAwait(false);
        }


        private JsonRpcResponse BuildErrorResponse(Exception ex, object? id)
        {
            // Protocol errors carry their own message and data; anything else is reported generically so internal
            // details (exception messages from handlers or stores) never reach the caller. The detail is logged.
            if (!(ex is IJsonRpcErrorProvider))
            {
                LogMessage($"A2A internal error: {ex}");
            }

            JsonRpcError error = ex is IJsonRpcErrorProvider provider
                ? provider.ToJsonRpcError()
                : new JsonRpcError { Code = (int)A2AErrorCode.InternalError, Message = "Internal error" };

            return new JsonRpcResponse { Id = id, Error = error };
        }

        private async Task SendJsonAsync(HttpListenerContext context, object value, CancellationToken token)
        {
            string json = JsonSerializer.Serialize(value, A2AJson.DefaultOptions);
            byte[] buffer = Encoding.UTF8.GetBytes(json);
            context.Response.ContentType = "application/json";
            context.Response.ContentLength64 = buffer.Length;
            await context.Response.OutputStream.WriteAsync(buffer, 0, buffer.Length, token).ConfigureAwait(false);
            context.Response.Close();
        }

        private async Task SendTextAsync(HttpListenerContext context, int statusCode, string text, CancellationToken token)
        {
            byte[] buffer = Encoding.UTF8.GetBytes(text);
            context.Response.StatusCode = statusCode;
            context.Response.ContentType = "text/plain";
            context.Response.ContentLength64 = buffer.Length;
            await context.Response.OutputStream.WriteAsync(buffer, 0, buffer.Length, token).ConfigureAwait(false);
            context.Response.Close();
        }

        private static async Task SendSseJsonAsync(HttpListenerResponse response, object value, CancellationToken token)
        {
            string json = JsonSerializer.Serialize(value, A2AJson.DefaultOptions);
            byte[] buffer = Encoding.UTF8.GetBytes($"data: {json}\n\n");
            await response.OutputStream.WriteAsync(buffer, 0, buffer.Length, token).ConfigureAwait(false);
            await response.OutputStream.FlushAsync(token).ConfigureAwait(false);
        }

        private void AddCors(HttpListenerContext context)
        {
            HttpAccessGuard.ApplyCorsHeaders(context, EnableCors, CorsHeaders);
        }

        private static bool IsPublicAgentCardRequest(HttpListenerRequest request)
        {
            return request.HttpMethod == "GET" && StringComparer.OrdinalIgnoreCase.Equals(request.Url?.AbsolutePath, A2AProtocol.AgentCardPath);
        }

        private static string NormalizePath(string path)
        {
            if (String.IsNullOrWhiteSpace(path)) return "/";
            return path.StartsWith("/", StringComparison.Ordinal) ? path : "/" + path;
        }

        private static int? TryParseInt(string? value)
        {
            return Int32.TryParse(value, out int parsed) ? parsed : null;
        }

        private static bool? TryParseBool(string? value)
        {
            return Boolean.TryParse(value, out bool parsed) ? parsed : null;
        }

        private static DateTimeOffset? TryParseDateTimeOffset(string? value)
        {
            return DateTimeOffset.TryParse(value, out DateTimeOffset parsed) ? parsed : null;
        }

        private static TaskState? TryParseTaskState(string? value)
        {
            if (String.IsNullOrWhiteSpace(value))
            {
                return null;
            }

            try
            {
                return JsonSerializer.Deserialize<TaskState>($"\"{value}\"", A2AJson.DefaultOptions);
            }
            catch (JsonException)
            {
                return null;
            }
        }

        private static bool IsTerminal(TaskState state)
        {
            return state == TaskState.Completed ||
                state == TaskState.Failed ||
                state == TaskState.Canceled ||
                state == TaskState.Rejected;
        }

        private void LogMessage(string message)
        {
            Log?.Invoke(this, $"[{DateTime.UtcNow:HH:mm:ss.fffZ}] {message}");
        }
    }

    internal static class A2ATaskProjection
    {
        public static AgentTask? Apply(AgentTask? current, StreamResponse response, A2ARequestContext context)
        {
            if (response.Task != null)
            {
                return response.Task.Clone();
            }

            if (response.Message != null)
            {
                return current;
            }

            if (response.StatusUpdate != null)
            {
                AgentTask task = current ?? new AgentTask
                {
                    Id = response.StatusUpdate.TaskId,
                    ContextId = response.StatusUpdate.ContextId,
                    History = new List<Message>(),
                    Artifacts = new List<Artifact>()
                };

                task.Status = response.StatusUpdate.Status;
                task.Metadata = Merge(task.Metadata, response.StatusUpdate.Metadata);
                if (context.Message != null && (task.History == null || !task.History.Any(message => message.MessageId == context.Message.MessageId)))
                {
                    task.History ??= new List<Message>();
                    task.History.Add(context.Message);
                }

                if (response.StatusUpdate.Status.Message != null)
                {
                    task.History ??= new List<Message>();
                    task.History.Add(response.StatusUpdate.Status.Message);
                }

                return task;
            }

            if (response.ArtifactUpdate != null)
            {
                TaskArtifactUpdateEvent update = response.ArtifactUpdate;
                AgentTask task = current ?? new AgentTask
                {
                    Id = update.TaskId,
                    ContextId = update.ContextId,
                    Status = new TaskStatus { State = TaskState.Working, Timestamp = DateTimeOffset.UtcNow },
                    History = new List<Message>(),
                    Artifacts = new List<Artifact>()
                };

                task.Artifacts ??= new List<Artifact>();
                Artifact? existing = task.Artifacts.FirstOrDefault(artifact => artifact.ArtifactId == update.Artifact.ArtifactId);
                if (existing != null && update.Append)
                {
                    existing.Parts.AddRange(update.Artifact.Parts);
                    existing.Metadata = Merge(existing.Metadata, update.Artifact.Metadata);
                }
                else
                {
                    task.Artifacts.RemoveAll(artifact => artifact.ArtifactId == update.Artifact.ArtifactId);
                    task.Artifacts.Add(update.Artifact);
                }

                task.Metadata = Merge(task.Metadata, update.Metadata);
                return task;
            }

            return current;
        }

        private static Dictionary<string, object?>? Merge(Dictionary<string, object?>? left, Dictionary<string, object?>? right)
        {
            if (right == null || right.Count == 0)
            {
                return left;
            }

            Dictionary<string, object?> merged = left != null
                ? new Dictionary<string, object?>(left, StringComparer.Ordinal)
                : new Dictionary<string, object?>(StringComparer.Ordinal);
            foreach (KeyValuePair<string, object?> item in right)
            {
                merged[item.Key] = item.Value;
            }

            return merged;
        }
    }

    internal sealed class A2ATaskEventNotifier
    {
        private readonly object _Lock = new object();
        private readonly Dictionary<string, List<Channel<StreamResponse>>> _Channels = new Dictionary<string, List<Channel<StreamResponse>>>(StringComparer.Ordinal);

        public Channel<StreamResponse> CreateChannel(string taskId)
        {
            Channel<StreamResponse> channel = Channel.CreateUnbounded<StreamResponse>();
            lock (_Lock)
            {
                if (!_Channels.TryGetValue(taskId, out List<Channel<StreamResponse>>? channels))
                {
                    channels = new List<Channel<StreamResponse>>();
                    _Channels[taskId] = channels;
                }

                channels.Add(channel);
            }

            return channel;
        }

        public void RemoveChannel(string taskId, Channel<StreamResponse> channel)
        {
            lock (_Lock)
            {
                if (_Channels.TryGetValue(taskId, out List<Channel<StreamResponse>>? channels))
                {
                    channels.Remove(channel);
                    if (channels.Count == 0)
                    {
                        _Channels.Remove(taskId);
                    }
                }
            }
        }

        public void Notify(string taskId, StreamResponse response)
        {
            List<Channel<StreamResponse>> channels;
            lock (_Lock)
            {
                if (!_Channels.TryGetValue(taskId, out List<Channel<StreamResponse>>? existing))
                {
                    return;
                }

                channels = existing.ToList();
            }

            foreach (Channel<StreamResponse> channel in channels)
            {
                channel.Writer.TryWrite(response);
            }
        }
    }
